#!/usr/bin/env node
/**
 * Fallback migration tool built on Prisma's official WebAssembly schema engine.
 *
 * Normal workflow: `pnpm prisma migrate dev` / `pnpm prisma migrate deploy`.
 * Those commands download a native schema-engine binary from binaries.prisma.sh.
 * In sandboxes or CI runners where that host is blocked, use this script instead:
 *
 *   node scripts/prisma-wasm.mjs diff <name>   create prisma/migrations/<ts>_<name>/migration.sql
 *   node scripts/prisma-wasm.mjs deploy        apply pending migrations (same _prisma_migrations table)
 *
 * The produced migrations are byte-compatible with `prisma migrate deploy`.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import 'dotenv/config';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const schemaPath = path.join(root, 'prisma', 'schema.prisma');
const migrationsDir = path.join(root, 'prisma', 'migrations');

const [, , command, nameArg] = process.argv;

if (command === 'generate-hint') {
  console.warn(
    '[prisma] `prisma generate` failed. If the engine download host is blocked, run:\n' +
      '  PRISMA_SCHEMA_ENGINE_BINARY=/bin/false pnpm prisma generate',
  );
  process.exit(0);
}

const url = process.env.DIRECT_DATABASE_URL || process.env.DATABASE_URL;
if (!url) {
  console.error('DATABASE_URL is not set');
  process.exit(1);
}

const { SchemaEngine } = await import('@prisma/schema-engine-wasm');
const { PrismaPg } = await import('@prisma/adapter-pg');
const { bindMigrationAwareSqlAdapterFactory } = await import('@prisma/driver-adapter-utils');

const schema = fs.readFileSync(schemaPath, 'utf8');
const adapter = bindMigrationAwareSqlAdapterFactory(new PrismaPg({ connectionString: url }));
const engine = await SchemaEngine.new(
  { datamodels: [['schema.prisma', schema]] },
  () => {},
  adapter,
);

function loadMigrations() {
  fs.mkdirSync(migrationsDir, { recursive: true });
  const dirs = fs
    .readdirSync(migrationsDir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();
  return {
    baseDir: migrationsDir,
    lockfile: {
      path: 'migration_lock.toml',
      content: fs.existsSync(path.join(migrationsDir, 'migration_lock.toml'))
        ? fs.readFileSync(path.join(migrationsDir, 'migration_lock.toml'), 'utf8')
        : null,
    },
    shadowDbInitScript: '',
    migrationDirectories: dirs.map((d) => ({
      path: d,
      migrationFile: {
        path: 'migration.sql',
        content: { tag: 'ok', value: fs.readFileSync(path.join(migrationsDir, d, 'migration.sql'), 'utf8') },
      },
    })),
  };
}

const filters = { externalTables: [], externalEnums: [] };

try {
  if (command === 'diff') {
    const list = loadMigrations();
    const from = list.migrationDirectories.length
      ? { tag: 'migrations', ...list }
      : { tag: 'empty' };
    const result = await engine.diff({
      from,
      to: { tag: 'schemaDatamodel', files: [{ path: 'schema.prisma', content: schema }] },
      script: true,
      exitCode: null,
      filters,
    });
    const sql = result.stdout ?? '';
    if (!sql.trim() || /This is an empty migration/.test(sql)) {
      console.log('No schema changes.');
    } else {
      const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
      const dir = path.join(migrationsDir, `${stamp}_${(nameArg || 'migration').replace(/\W+/g, '_')}`);
      fs.mkdirSync(dir, { recursive: true });
      fs.writeFileSync(path.join(dir, 'migration.sql'), sql);
      const lock = path.join(migrationsDir, 'migration_lock.toml');
      if (!fs.existsSync(lock)) {
        fs.writeFileSync(
          lock,
          '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
        );
      }
      console.log('Created', path.relative(root, dir));
    }
  } else if (command === 'deploy') {
    const out = await engine.applyMigrations({ migrationsList: loadMigrations(), filters });
    console.log(
      out.appliedMigrationNames.length
        ? 'Applied: ' + out.appliedMigrationNames.join(', ')
        : 'Database is up to date.',
    );
  } else {
    console.log('usage: prisma-wasm.mjs <diff [name] | deploy>');
    process.exitCode = 1;
  }
} catch (err) {
  console.error(err?.message ?? err);
  process.exitCode = 1;
} finally {
  engine.free?.();
}
